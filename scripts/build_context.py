from __future__ import annotations

import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from scripts.common import atomic_write_text, read_json, root_from_script, run_script
from scripts.records import research_focus, section


def _first_bullets(path: Path, maximum: int = 3) -> list[str]:
    if not path.is_file():
        return []
    items = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("- ") and "None yet" not in line:
            items.append(line)
        if len(items) >= maximum:
            break
    return items


def _goal_summary(text: str) -> str:
    lines = [line.rstrip() for line in text.splitlines()]
    kept: list[str] = []
    for line in lines:
        if line.startswith((
            "# Research Goal", "## Question", "## Decision", "## Success Criteria",
            "- Primary metric", "- Decision mode", "- Decision criterion",
            "- Baseline", "- Resource limit",
        )):
            kept.append(line)
        elif kept and line and not line.startswith("##") and len(kept) < 14:
            kept.append(line)
    return "\n".join(kept[:14]).strip()


def build_context(root: Path) -> Path:
    state = read_json(root / "research/STATE.json")
    goal_path = root / "research/GOAL.md"
    digest_path = root / "experiments/DIGEST.md"
    active_id = state.get("active_experiment")
    plan_audit_verdict = "none"
    decision_rule_status = "none"
    if active_id:
        manifest_path = root / "experiments/active" / active_id / "MANIFEST.json"
        if manifest_path.is_file():
            manifest = read_json(manifest_path)
            plan_audit = manifest.get("plan_audit")
            if isinstance(plan_audit, dict):
                plan_audit_verdict = str(plan_audit.get("verdict") or "none")
            decision_facts = manifest.get("decision_facts")
            if isinstance(decision_facts, dict):
                decision_rule_status = str(
                    decision_facts.get("rule_status") or "none"
                )
    unattended = state.get("unattended_loop", {})
    goal = goal_path.read_text(encoding="utf-8")
    focus_id = active_id or state.get("latest_completed_experiment")
    focus_record = ""
    focus_path = None
    if focus_id:
        area = "active" if active_id else "completed"
        focus_path = root / "experiments" / area / focus_id / "EXPERIMENT.md"
        if focus_path.is_file():
            focus_record = focus_path.read_text(encoding="utf-8")
    focus = research_focus(goal, focus_record)
    lines = [
        "# Current Research Context",
        "",
        "Generated by `scripts/build_context.py`. Do not edit manually.",
        "",
        "## Research Focus",
        "",
        "Current question: research/GOAL.md. Novelty is a claim to test, not a proven result.",
        f"Experiment source: {focus_path.relative_to(root) if focus_path else 'none'}.",
        *[f"- {key}: {' '.join(value.split())}" for key, value in focus.items()],
        "",
    ]
    maximum = int(state["budgets"].get("max_context_chars", 9000))
    if len("\n".join(lines)) > maximum - 80:
        raise ValueError(
            "context budget cannot preserve Research Focus; shorten sources or raise budget"
        )
    lines.extend([
        "## State",
        "",
        f"- Project: {state.get('project_id')}",
        f"- Project status: {state.get('project_status')}",
        f"- Active experiment: {active_id or 'none'}",
        f"- Phase: {state.get('phase') or 'none'}",
        f"- Stage: {state.get('stage') or 'none'}",
        f"- Independent review required: {str(bool(state.get('review_required'))).lower()}",
        f"- Baseline experiment: {state.get('baseline_experiment') or 'none'}",
        f"- Latest completed experiment: {state.get('latest_completed_experiment') or 'none'}",
        f"- Plan audit: {plan_audit_verdict}",
        f"- Mechanical rule status: {decision_rule_status}",
        f"- Unattended loop: {unattended.get('status', 'idle')}",
        f"- Unattended target: {unattended.get('target_experiment') or 'none'}",
        "",
        "## Next Action",
        "",
        f"- Mode: {state.get('next_action', {}).get('mode', 'unknown')}",
        f"- Queue: {state.get('next_action', {}).get('queue_id') or 'none'}",
        f"- Objective: {state.get('next_action', {}).get('objective', 'unknown')}",
        "",
        "## Goal Summary",
        "",
        _goal_summary(goal),
    ])
    if state.get("latest_aborted_experiment"):
        lines.extend(["", f"Latest aborted comparison: {state['latest_aborted_experiment']}."])
    if "agent_led_loop" in state:
        control = state["agent_led_loop"]
        lines.extend([
            "", f"Agent-led loop: {control.get('status', 'idle')}; "
            f"target: {control.get('target_experiment') or 'none'}. "
            "Saved progress is not authorization; use the dedicated router when requested.",
        ])
    memory_root = root / "research/memory"
    memory_lines = []
    for name, label in [
        ("INSIGHTS.md", "Insights"),
        ("DEAD_ENDS.md", "Dead ends"),
        ("OPEN_QUESTIONS.md", "Open questions"),
    ]:
        bullets = _first_bullets(memory_root / name)
        if bullets:
            memory_lines.append(f"- {label}: " + "; ".join(item[2:] for item in bullets))
    if memory_lines:
        lines.extend(["", "## Research Memory", "", *memory_lines])
    if active_id:
        active = root / "experiments/active" / active_id
        record = active / "EXPERIMENT.md"
        scope = active / "SCOPE.json"
        if record.is_file():
            text = focus_record
            lines.extend(
                [
                    "",
                    "## Active Hypothesis",
                    "",
                    section(text, "## Hypothesis"),
                    "",
                    "## Active Method",
                    "",
                    section(text, "## Method"),
                ]
            )
        if scope.is_file():
            payload = read_json(scope)
            paths = []
            for key in ("read_paths", "write_paths", "test_paths"):
                paths.extend(payload.get(key, []))
            lines.extend(
                [
                    "",
                    "## Scoped Paths",
                    "",
                    *[f"- `{path}`" for path in dict.fromkeys(paths)],
                ]
            )
    if digest_path.is_file():
        lines.extend([
            "", "## Completed Digest", "", digest_path.read_text(encoding="utf-8").strip(),
        ])
    text = "\n".join(lines).rstrip() + "\n"
    if len(text) > maximum:
        marker = "\n## Completed Digest\n"
        if marker in text:
            text = text.split(marker, 1)[0].rstrip() + "\n"
    if len(text) > maximum:
        text = text[: maximum - 80].rstrip() + "\n\n[Context truncated by configured limit.]\n"
    path = root / "research/CONTEXT.md"
    atomic_write_text(path, text)
    return path


def _execute() -> str:
    root = root_from_script()
    return build_context(root).relative_to(root).as_posix()


if __name__ == "__main__":
    raise SystemExit(run_script("build-context", _execute))
